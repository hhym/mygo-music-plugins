function parseTracks(html, options = {}) {
  const out = [];
  const seen = new Set();
  const blocks = options.blocks || /<li[\s\S]*?<\/li>/gi;
  const blockList = String(html).match(blocks) || [];
  const strict = blockList.filter((block) => /mname|aleft|m_name|class="source"/i.test(block));
  const chosen = strict.length ? strict : blockList;
  for (const block of chosen) {
    const link = /<a[^>]*href="\/play\/(\d+)\.html"[^>]*>([\s\S]*?)<\/a>/i.exec(block);
    if (!link) continue;
    const id = link[1];
    if (seen.has(id)) continue;
    const tag = link[0];
    const title = /title="([^"]*)"/i.exec(tag);
    const artistMatch = /<a[^>]*href="\/artist\/(\d+)\.html"[^>]*>([\s\S]*?)<\/a>/i.exec(block);
    const item = trackFromLink(id, title ? title[1] : "", link[2]);
    if (artistMatch && !item.artists.length) item.artists = [{ id: artistMatch[1], name: clean(artistMatch[2]) }];
    if (!item.artists.length && options.artist) item.artists = [{ id: String(options.artist.id || ""), name: options.artist.name }];
    seen.add(id);
    out.push(item);
  }
  return out;
}

function parseAlbumCards(html) {
  const out = [];
  const seen = new Set();
  for (const block of String(html).match(/<li[\s\S]*?<\/li>/gi) || []) {
    const link = /<a[^>]*href="\/malbum\/(\d+)\.html"[^>]*>([\s\S]*?)<\/a>/i.exec(block);
    if (!link || seen.has(link[1])) continue;
    const title = /title="([^"]*)"/i.exec(link[0]);
    const img = /<img[^>]*src="([^"]+)"/i.exec(block);
    seen.add(link[1]);
    out.push({
      id: link[1],
      name: clean(title ? title[1] : link[2]),
      imageUrl: img ? absolute(img[1]) : "",
      artists: [],
    });
  }
  return out;
}

function parseArtistCards(html) {
  const out = [];
  const seen = new Set();
  for (const block of String(html).match(/<li[\s\S]*?<\/li>/gi) || []) {
    const link = /<a[^>]*href="\/artist\/(\d+)\.html"[^>]*>([\s\S]*?)<\/a>/i.exec(block);
    if (!link || seen.has(link[1])) continue;
    const title = /title="([^"]*)"/i.exec(link[0]);
    const img = /<img[^>]*src="([^"]+)"/i.exec(block);
    seen.add(link[1]);
    out.push({
      id: link[1],
      name: clean(title ? title[1] : link[2]),
      imageUrl: img ? absolute(img[1]) : "",
    });
  }
  return out;
}

function parseHome(html) {
  const seen = new Set();
  const tracks = [];
  for (const match of String(html).matchAll(/<a[^>]*href="\/play\/(\d+)\.html"[^>]*>([\s\S]*?)<\/a>/gi)) {
    if (seen.has(match[1])) continue;
    seen.add(match[1]);
    const title = /title="([^"]*)"/i.exec(match[0]);
    tracks.push(trackFromLink(match[1], title ? title[1] : "", match[2]));
  }
  const albums = parseAlbumCards(html);
  return { tracks, albums };
}

function parseCategory(html, slug, page) {
  const title = CATEGORIES[slug] || t("歌曲列表");
  let tracks = parseTracks(html);
  if (!tracks.length) {
    const seen = new Set();
    for (const match of String(html).matchAll(TITLE_ATTR)) {
      if (seen.has(match[1])) continue;
      seen.add(match[1]);
      tracks.push(track(match[1], /title="([^"]*)"/i.exec(match[0])?.[1] || ""));
    }
  }
  return { title, tracks, page };
}

function parseDetail(html, id) {
  const name =
    clean((/var\s+music_name\s*=\s*"([^"]*)"/i.exec(html) || [])[1]) ||
    clean((/<li[^>]*id="songname"[^>]*>([\s\S]*?)<\/li>/i.exec(html) || [])[1]) ||
    clean((/<h1[^>]*>([\s\S]*?)<\/h1>/i.exec(html) || [])[1]);
  const artist =
    clean((/所属歌手[\s\S]{0,120}?<a[^>]*title="([^"]*)"/i.exec(html) || [])[1]) ||
    clean((/<div class="source"[^>]*>[\s\S]*?<a[^>]*>([\s\S]*?)<\/a>/i.exec(html) || [])[1]) ||
    clean((/<a[^>]*href="\/artist\/\d+\.html"[^>]*>([\s\S]*?)<\/a>/i.exec(html) || [])[1]);
  return track(id, name, artist);
}

