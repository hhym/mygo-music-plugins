let gbkBytes = null;
let gbkReverse = null;

function gbkBinary() {
  if (!gbkBytes) gbkBytes = atob(GBK_TABLE.replace(/\s+/g, ""));
  return gbkBytes;
}

function gbkCode(index) {
  const b = gbkBinary();
  const i = index * 2;
  if (i + 1 >= b.length) return 0xfffd;
  return (b.charCodeAt(i) << 8) | b.charCodeAt(i + 1);
}

function decodeGbk(buffer) {
  const bytes = new Uint8Array(buffer);
  let out = "";
  for (let i = 0; i < bytes.length; i++) {
    const b = bytes[i];
    if (b < 0x80) out += String.fromCharCode(b);
    else if (b === 0x80) out += "\u20ac";
    else if (b >= 0x81 && b <= 0xfe && i + 1 < bytes.length) {
      const trail = bytes[++i];
      if (trail >= 0x40 && trail <= 0xfe && trail !== 0x7f) {
        const index = (b - 0x81) * 190 + (trail < 0x7f ? trail - 0x40 : trail - 0x41);
        const cp = gbkCode(index);
        out += cp === 0xfffd ? "\ufffd" : String.fromCharCode(cp);
      } else {
        out += "\ufffd";
      }
    } else out += "\ufffd";
  }
  return out;
}

function encodeGbk(text) {
  if (!gbkReverse) {
    gbkReverse = new Map();
    for (let i = 0; i < 23940; i++) {
      const cp = gbkCode(i);
      if (cp !== 0xfffd) {
        const ch = String.fromCharCode(cp);
        if (!gbkReverse.has(ch)) {
          const lead = 0x81 + Math.floor(i / 190);
          const j = i % 190;
          const trail = j < 63 ? 0x40 + j : 0x80 + (j - 63);
          gbkReverse.set(ch, [lead, trail]);
        }
      }
    }
  }
  const bytes = [];
  for (const ch of String(text || "")) {
    const cp = ch.codePointAt(0);
    if (cp < 0x80) bytes.push(cp);
    else if (cp === 0x20ac) bytes.push(0x80);
    else {
      const pair = gbkReverse.get(ch);
      if (pair) bytes.push(pair[0], pair[1]);
    }
  }
  return bytes;
}

function gbkQuery(text) {
  return encodeGbk(text)
    .map((b) => "%" + b.toString(16).toUpperCase().padStart(2, "0"))
    .join("");
}

// --- 通用工具 --------------------------------------------------------------
function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function fail(code, message) {
  const error = new Error(message || code);
  error.code = code;
  return error;
}

function clean(value) {
  return String(value || "")
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<style[\s\S]*?<\/style>/gi, "")
    .replace(/<[^>]+>/g, "")
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => {
      const cp = parseInt(hex, 16);
      return cp > 0 && cp <= 0x10ffff ? String.fromCodePoint(cp) : "";
    })
    .replace(/&#(\d+);/g, (_, dec) => {
      const cp = parseInt(dec, 10);
      return cp > 0 && cp <= 0x10ffff ? String.fromCodePoint(cp) : "";
    })
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeName(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[\s'"“”‘’·・.,，。!！?？:：;；_\-—–()（）\[\]【】{}<>《》/\\|@#$%^&*+=~`]/g, "")
    .replace(/dj[^版]{0,12}版/g, "")
    .trim();
}

function baseName(value) {
  return normalizeName(
    String(value || "")
      .replace(/[（(][^）)]*[）)]/g, "")
      .replace(/dj[^版]{0,12}版/gi, ""),
  );
}

function absolute(url) {
  if (!url) return "";
  if (/^https?:\/\//i.test(url)) return url;
  if (url.startsWith("//")) return "http:" + url;
  return BASE + (url.startsWith("/") ? url : "/" + url);
}

function track(id, name, artist, albumName) {
  return {
    id: String(id),
    name: clean(name) || "未知歌曲",
    artists: artist ? [{ id: "", name: clean(artist) }] : [],
    album: { id: "", name: clean(albumName) || t("米粒音乐"), imageUrl: "" },
    duration: 0,
    url: `${BASE}/play/${id}.html`,
  };
}

function splitArtist(text) {
  const value = clean(text);
  const at = value.lastIndexOf(" - ");
  if (at > 0) return [value.slice(0, at).trim(), value.slice(at + 3).trim()];
  const at2 = value.lastIndexOf("-");
  if (at2 > 0 && value.length - at2 < 28) return [value.slice(0, at2).trim(), value.slice(at2 + 1).trim()];
  return [value, ""];
}

function trackFromLink(id, title, text) {
  let name = clean(title) || clean(text);
  let artist = "";
  const body = clean(text);
  if (body.includes(" - ")) {
    const [bodyName, bodyArtist] = splitArtist(body);
    if (name && bodyName && (name === bodyName || name.startsWith(bodyName))) {
      artist = bodyArtist;
      if (name === bodyName) [, artist] = splitArtist(bodyName);
      if (artist) {
        const [, embedded] = splitArtist(name);
        if (name.includes("-") && !name.includes(" - ")) {
          const pair = splitArtist(name);
          name = pair[0];
          artist = pair[1] || artist;
        }
      }
    }
  }
  if (!artist && name.includes(" - ")) [name, artist] = splitArtist(name);
  if (!artist && /[^-]{2,}-[^-]{2,}$/.test(name)) {
    const pair = splitArtist(name);
    if (pair[1]) [name, artist] = pair;
  }
  return track(id, name, artist);
}

