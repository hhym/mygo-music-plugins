async function neteaseSearch(item) {
  const artist = item.artists && item.artists[0] ? item.artists[0].name : "";
  const key = `${item.name}|${artist}`;
  const hit = neteaseCache.get(key);
  if (hit && Date.now() - hit.at < 30 * 60 * 1000) return hit.id;
  const query = `${item.name} ${artist}`.trim();
  const url = `${NETEASE_SEARCH}?s=${encodeURIComponent(query)}&type=1&limit=15&offset=0`;
  let data;
  try {
    data = await jsonFetch(url, { referer: NETEASE_REFERER });
  } catch (error) {
    return "";
  }
  const songs = (data && data.result && data.result.songs) || [];
  const wanted = baseName(item.name);
  const wantedArtist = normalizeName(artist);
  let best = null;
  let bestScore = -1;
  for (const song of songs) {
    const name = baseName((song.name || "").replace(/<[^>]+>/g, ""));
    const artists = (song.artists || song.ar || []).map((a) => a.name).join("");
    let score = 0;
    if (name === wanted) score += 90;
    else if (name.includes(wanted) || wanted.includes(name)) score += 55;
    else continue;
    if (wantedArtist && normalizeName(artists).includes(wantedArtist)) score += 40;
    if (song.duration && Math.abs(song.duration - (item.duration || 0)) < 5000 && item.duration) score += 5;
    if (score > bestScore) {
      bestScore = score;
      best = song;
    }
  }
  const id = best ? String(best.id) : "";
  neteaseCache.set(key, { id, at: Date.now() });
  return id;
}

async function neteaseMp3(songId) {
  const hit = neteaseUrlCache.get(songId);
  if (hit && Date.now() - hit.at < 30 * 60 * 1000) return hit.url;
  const outer = `https://music.163.com/song/media/outer/url?id=${songId}.mp3`;
  try {
    const response = await fetch(outer, {
      headers: {
        "user-agent": UA,
        referer: NETEASE_REFERER,
        range: "bytes=0-0",
      },
    });
    const type = response.headers.get("content-type") || "";
    if ((response.ok || response.status === 206) && /audio/i.test(type)) {
      const finalUrl = response.url && response.url.startsWith("http") ? response.url : outer;
      const url = finalUrl.replace(/^http:\/\//i, "https://");
      neteaseUrlCache.set(songId, { url, at: Date.now() });
      return url;
    }
  } catch (error) {
    // 外链不可用时仍返回 outer 地址，播放器会自行跟随重定向
  }
  return outer;
}

async function neteaseLyric(songId) {
  const url = `${NETEASE_LYRIC}?id=${songId}&lv=-1&kv=-1&tv=-1`;
  try {
    const data = await jsonFetch(url, { referer: NETEASE_REFERER });
    const lrc = data && data.lrc && data.lrc.lyric ? data.lrc.lyric : "";
    return { lrc };
  } catch (error) {
    return {};
  }
}

