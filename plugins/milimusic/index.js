async function fetchText(path, cache = true) {
  const url = path.startsWith("http") ? path : BASE + path;
  const hit = pageCache.get(url);
  if (cache && hit && Date.now() - hit.at < PAGE_TTL) return hit.text;
  let lastError = null;
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const response = await fetch(url, {
        headers: {
          "user-agent": UA,
          referer: REFERER,
          accept: "text/html,application/xhtml+xml,*/*",
        },
      });
      if (response.ok) {
        const buffer = await response.arrayBuffer();
        const type = response.headers.get("content-type") || "";
        const text = /charset=utf-?8/i.test(type)
          ? new TextDecoder("utf-8").decode(buffer)
          : decodeGbk(buffer);
        if (cache) pageCache.set(url, { text, at: Date.now() });
        return text;
      }
      lastError = fail("unavailable", `站点返回 ${response.status}`);
    } catch (error) {
      lastError = error;
    }
    await sleep(600 + attempt * 700);
  }
  throw lastError || fail("unavailable", "站点暂时无法访问");
}

async function jsonFetch(url, headers) {
  const response = await fetch(url, {
    headers: {
      "user-agent": UA,
      accept: "application/json,text/plain,*/*",
      ...headers,
    },
  });
  if (!response.ok) throw fail("unavailable", `网易云返回 ${response.status}`);
  return response.json();
}

